//汉诺塔问题——>递归算法
/*对于任何一个大于1的整数n，要解决n层汉诺塔问题都可以化解为两个n-1层汉诺塔问题
（因为任意一个n>2的正整数，都可以将最底层当作参照物，
然后就可以分解为两个n-1层汉诺塔问题了）*/
#include <stdio.h>
void Hanoi(int n,char a,char b,char c);
void Move(int k,char m,char n);//k号盘子从m移动到n

/*算法是（图灵机的）解题步骤，
没有算法解决的问题叫做不可解决问题或不可计算问题，
直观上可以有效计算的问题图灵机都可以计算*/

void Move(int k,char m,char n){
    printf("Move%d:%c-->%c\n",k,m,n);
}

void Hanoi(int n,char a,char b,char c){
    if(n==1){
        Move(n,a,c);
    }
    else{
        Hanoi(n-1,a,c,b);
        Move(n,a,c);
        Hanoi(n-1,b,a,c);
    }
}
/*这是解决汉诺塔问题的核心递归函数。
参数n表示需要移动的盘子数量，a、b、c分别表示三个柱子。
如果只有一个盘子（n==1），直接调用Move函数将盘子从a柱子移动到c柱子。
如果有多于一个盘子，按照以下步骤递归操作：
首先，将a柱子上的前n-1个盘子通过c柱子移动到b柱子上（Hanoi(n-1, a, c, b)）。
然后，将最大的盘子（第n个盘子）从a柱子移动到c柱子上（Move(n, a, c)）。
最后，将b柱子上的n-1个盘子通过a柱子移动到c柱子上（Hanoi(n-1, b, a, c)）。*/

/*现在，让我们来看为什么在程序进行时第一步进行从5到4是b、c交换位置：
初始状态：5个盘子在A柱子上。
第一步：我们需要将A柱子上的4个盘子（即除了最大的盘子）移动到B柱子上，使用C柱子作为辅助。这是通过递归调用Hanoi(4, 'A', 'C', 'B')实现的。
在这一步中，A柱子上的4个盘子需要被移动到B柱子上，这意味着我们需要将A柱子上的3个盘子移动到C柱子上（Hanoi(3, 'A', 'B', 'C')），
然后移动第4个盘子（Move(4, 'A', 'B')），最后将C柱子上的3个盘子移动到B柱子上（Hanoi(3, 'C', 'A', 'B')）。
在将A柱子上的3个盘子移动到C柱子上的过程中，我们需要将A柱子上的2个盘子移动到B柱子上（Hanoi(2, 'A', 'C', 'B')），
然后移动第3个盘子（Move(3, 'A', 'C')），最后将B柱子上的2个盘子移动到C柱子上（Hanoi(2, 'B', 'A', 'C')）。
在这个过程中，你会看到b和c柱子的角色在递归调用中交替出现。这是因为在每一步递归中，我们都需要将一个柱子上的盘子移动到另一个柱子上，
同时使用第三个柱子作为辅助。这就是为什么在程序进行时，你会看到b和c柱子的位置在递归调用中交替出现。*/

int main(){
    Hanoi(64,'A','B','C');
    return 0;
}

