//递归方法
#include<stdio.h>
//递归函数，计算将n分成k份，每份最小值不小于min_val的划分方法数
/*为了确保不产生重复的划分方案，我们在递归过程中引入 min_val 来约束每份的取值范围。
具体来说，在每次递归调用时，我们从 min_val 开始枚举每份可能的取值。
这样能保证划分出来的数是单调递增的（不递减），从而避免出现重复的组合。
比如，当我们已经确定前面一份是 1 时，后面枚举的数就不会小于 1，这样就不会出现 1,5,1 这种和 1,1,5 重复的情况。*/
int f(int n, int k, int min_val);
int f(int n, int k, int min_val){
    if(n < k)return 0;//无法划分
    if(k == 1)return 1;//只有一种划分方法
    int count = 0;
    for(int i = min_val; i <= n / k; i++){
/*n / k 是一个合理的上限。因为要将 n 平均分成 k 份，每份最大可能的值不会超过 n / k（这里是整数除法）。
如果 i 大于 n / k，那么剩下的数就无法再分成 k - 1 份，也就不符合划分的要求了。*/
        count += f(n - i, k - 1, i);
/*n - i：当我们确定当前一份的值为 i 后，剩下需要划分的数就是 n - i。
每次递归调用 f(n - i, k - 1, i) 会返回将 n - i 分成 k - 1 份且每份最小值不小于 i 的划分方法数。*/
    }
    return count;
}
int main(){
    int n, k;
    scanf("%d %d",&n, &k);
    int result = f(n, k, 1);
    printf("%d\n",result);
    return 0;
}
